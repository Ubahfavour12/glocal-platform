/**
 * Regenerate the facts at the top of STATUS.md from the repo itself.
 *
 * A status file that is written by hand goes stale, and a stale status file is
 * worse than none: it is confidently wrong, and it gets believed. So the parts
 * that can be derived are derived, every time, and the parts that need judgement
 * (what is blocked, what is next) stay hand-written below the marker.
 *
 * Run with `npm run status`. Safe to run any time; it only rewrites the block
 * between the two markers.
 */

import { execSync } from "node:child_process";
import { readFileSync, writeFileSync, readdirSync } from "node:fs";

const START = "<!-- AUTO:START -->";
const END = "<!-- AUTO:END -->";

const sh = (cmd) => {
  try {
    return execSync(cmd, { encoding: "utf8", stdio: ["ignore", "pipe", "ignore"] }).trim();
  } catch {
    return "";
  }
};

// Tests: run them rather than trusting a number someone typed last week.
let tests = "not run";
const out = sh("npx vitest run --reporter=basic 2>&1") || sh("npx vitest run 2>&1");
const m = out.match(/Tests\s+(\d+)\s+passed(?:\s*\|\s*(\d+)\s+skipped)?/);
if (m) tests = `**${m[1]} passing**${m[2] ? `, ${m[2]} skipped` : ""}`;
else if (/FAIL|failed/i.test(out)) tests = "**FAILING** — run `npx vitest run`";

// Reads the directory, so this is what the REPO carries, not what the database
// has run. It said "applied" for a long time and could never have known: a file
// existing here and a function existing in Postgres are different facts, and
// conflating them is exactly the confident wrongness this file exists to avoid.
const migrations = readdirSync("supabase/migrations").filter((f) => f.endsWith(".sql")).sort();
const branch = sh("git rev-parse --abbrev-ref HEAD") || "unknown";
const commits = sh("git rev-list --count HEAD") || "?";
const local = sh("git rev-parse --short HEAD");
const remote = sh(`git rev-parse --short origin/${branch}`);
const synced = local && remote && local === remote ? "in sync with GitHub" : "**not pushed**";
const dirty = sh("git status --porcelain");

const today = new Date().toLocaleDateString("en-GB", {
  day: "numeric", month: "long", year: "numeric",
});

const block = `${START}
| | |
|---|---|
| Tests | ${tests} |
| Migrations in repo | through \`${(migrations.at(-1) ?? "none").replace(".sql", "")}\` |
| Commits | ${commits} on \`${branch}\` |
| GitHub | ${synced} |
| Uncommitted changes | ${dirty ? `**yes** — ${dirty.split("\n").length} file(s)` : "none"} |
| Live at | gg-platform-dun.vercel.app |

_Facts above regenerated by \`npm run status\` on ${today}._
${END}`;

const path = "STATUS.md";
const file = readFileSync(path, "utf8");
if (!file.includes(START)) {
  console.error(`STATUS.md is missing the ${START} marker; not touching it.`);
  process.exit(1);
}
// Plain slicing rather than a regex replace: the block contains backticks and
// dollar signs, and String.replace treats several `$` sequences in the
// REPLACEMENT as special, which silently ate the whole thing.
const a = file.indexOf(START);
const b = file.indexOf(END);
if (a === -1 || b === -1 || b < a) {
  console.error("STATUS.md markers are missing or out of order; not touching it.");
  process.exit(1);
}
writeFileSync(path, file.slice(0, a) + block + file.slice(b + END.length));
console.log("STATUS.md facts refreshed.");
