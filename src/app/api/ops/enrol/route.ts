import { NextRequest, NextResponse } from "next/server";
import { createClient, createServiceClient } from "@/lib/supabase/server";
import { configuredFounders, isFounder } from "@/lib/admin/access";
import { ADMIN_COOKIE, ADMIN_SESSION_MS, issueAdminSession } from "@/lib/admin/session";
import { base32Decode, describeClockSkew, diagnoseTotp } from "@/lib/admin/totp";
import { enrolOpsCredentials, opsEnrolled, pendingEnrolment } from "@/lib/admin/credentials";

/**
 * Save a second factor, once, after proving it works.
 *
 * THE ORDER IS STILL THE SAFETY PROPERTY. The code is verified before
 * anything is promoted, so the only way to enrol a key is to demonstrate you
 * already hold it. A key that never reached the phone cannot become the one
 * that locks everybody out.
 *
 * WHAT CHANGED, AND WHY IT HAD TO. The secret used to arrive in the request
 * body, generated by the page that rendered the form. That made the flow
 * unusable in the one way nobody tests for: the page regenerated the key on
 * every render, so coming back from the authenticator app to a re-fetched
 * page meant the phone held one key and the form posted another. The server
 * dutifully compared the code against the key it was given, found no match,
 * and reported a wrong code. The key was never wrong.
 *
 * Now the candidate is read server-side, from the row the page is displaying
 * from. The browser sends six digits; there is one key they can be checked
 * against; and a mismatch means what it says.
 *
 * FIRST RUN ONLY. Once a credential exists this refuses, whoever is asking.
 * Replacing a second factor must not be something a single compromised inbox
 * can do; that needs a deliberate reset with access to the database.
 */
export async function POST(req: NextRequest) {
  const supabase = await createClient();
  const {
    data: { user },
  } = await supabase.auth.getUser();
  if (!user?.email || !isFounder(user.email, configuredFounders())) {
    return NextResponse.json({ error: "that did not work" }, { status: 401 });
  }

  if (await opsEnrolled()) {
    return NextResponse.json(
      { error: "a second factor is already set up" },
      { status: 409 },
    );
  }

  const body = (await req.json().catch(() => null)) as { code?: string } | null;

  const candidate = await pendingEnrolment();
  if (!candidate) {
    return NextResponse.json(
      { error: "that setup key has expired — reload this page and add the new one" },
      { status: 409 },
    );
  }

  // Never promote something that cannot later authenticate anyone. A secret
  // too short, not base32, or a signing key with no entropy would enrol
  // successfully and then refuse every code forever.
  let decoded = 0;
  try {
    decoded = base32Decode(candidate.totpSecret).length;
  } catch {
    decoded = 0;
  }
  if (decoded < 16 || candidate.sessionSecret.length < 32) {
    return NextResponse.json({ error: "that did not work" }, { status: 400 });
  }

  const verdict = diagnoseTotp(candidate.totpSecret, String(body?.code ?? ""));
  if (verdict.match === "out_of_window") {
    return NextResponse.json({ error: describeClockSkew(verdict.offsetSeconds) }, { status: 401 });
  }
  if (verdict.match !== "in_window") {
    return NextResponse.json(
      {
        error:
          "that code did not match the key shown above — delete the Glocal entry in your authenticator, then add this key again (type based on time, not a counter)",
      },
      { status: 401 },
    );
  }

  const saved = await enrolOpsCredentials(
    candidate.totpSecret,
    candidate.sessionSecret,
    user.email,
  );
  if (!saved.ok) {
    return NextResponse.json({ error: "could not save, try again" }, { status: 500 });
  }

  try {
    await createServiceClient().from("audit_log").insert({
      actor: `ops:${user.id}`,
      action: "ops_enrolled",
      detail: { email: user.email },
    });
  } catch {
    /* the enrolment stands regardless */
  }

  // Straight in, rather than asking for a second code they would have to
  // wait thirty seconds for. They have just proved they hold the phone.
  const value = issueAdminSession(user.email, candidate.sessionSecret);
  const res = NextResponse.json({ ok: true });
  if (value) {
    res.cookies.set(ADMIN_COOKIE, value, {
      httpOnly: true,
      sameSite: "strict",
      secure: process.env.NODE_ENV === "production",
      path: "/",
      maxAge: Math.floor(ADMIN_SESSION_MS / 1000),
    });
  }
  return res;
}
